module top_module(
    input clk,
    input areset,
    input bump_left,
    input bump_right,
    input ground,
    input dig,
    output reg walk_left,
    output reg walk_right,
    output reg aaah,
    output reg splatter
);

    parameter IDLE = 3'b000;
    parameter WALK_LEFT = 3'b001;
    parameter WALK_RIGHT = 3'b010;
    parameter FALLING = 3'b011;
    parameter DIGGING = 3'b100;
    parameter SPLATTERED = 3'b101;
    
    reg [2:0] state, next_state;
    reg [5:0] fall_counter;
    
    always @(posedge clk or posedge areset) begin
        if (areset) begin
            state <= IDLE; // Initialize to IDLE, which will transition to WALK_LEFT on the next clock
            walk_left <= 1'b1;
            walk_right <= 1'b0;
            aaah <= 1'b0;
            splatter <= 1'b0;
            fall_counter <= 6'b0;
        end else begin
            state <= next_state;
        end
    end

    always @(*) begin
        next_state = state;
        walk_left = walk_left;
        walk_right = walk_right;
        aaah = 1'b0;
        
        case (state)
            IDLE: begin
                next_state = WALK_LEFT; // Start walking left after reset
            end
            WALK_LEFT: begin
                if (!ground) begin
                    next_state = FALLING;
                    aaah = 1'b1;
                end else if (dig) begin
                    next_state = DIGGING;
                end else if (bump_right) begin
                    next_state = WALK_RIGHT;
                    walk_left = 1'b0;
                    walk_right = 1'b1;
                end
            end
            WALK_RIGHT: begin
                if (!ground) begin
                    next_state = FALLING;
                    aaah = 1'b1;
                end else if (dig) begin
                    next_state = DIGGING;
                end else if (bump_left) begin
                    next_state = WALK_LEFT;
                    walk_left = 1'b1;
                    walk_right = 1'b0;
                end
            end
            FALLING: begin
                aaah = 1'b1;
                fall_counter = fall_counter + 1;
                if (ground) begin
                    if (fall_counter > 6'd20) {
                        next_state = SPLATTERED;
                        splatter = 1'b1;
                        walk_left = 1'b0;
                        walk_right = 1'b0;
                    } else {
                        if (walk_left) {
                            next_state = WALK_LEFT;
                        } else {
                            next_state = WALK_RIGHT;
                        }
                    }
                    fall_counter = 6'b0;
                end
            end
            DIGGING: begin
                if (!ground) begin
                    next_state = FALLING;
