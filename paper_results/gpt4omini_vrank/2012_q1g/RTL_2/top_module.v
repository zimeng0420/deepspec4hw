module top_module (
    input [4:1] x,
    output logic f
);
    assign f = (x[1] == 0 && x[2] == 0 && x[3] == 0 && x[4] == 0) || // 1 for (00, 00)
                (x[1] == 0 && x[2] == 0 && x[3] == 1 && x[4] == 0) || // 1 for (00, 10)
                (x[1] == 1 && x[2] == 1 && x[3] == 1 && x[4] == 0) || // 1 for (11, 01)
                (x[1] == 1 && x[2] == 1 && x[3] == 0 && x[4] == 0) || // 1 for (10, 00)
                (x[1] == 1 && x[2] == 0 && x[3] == 1 && x[4] == 0) || // 0 for (01, 00)
                (x[1] == 0 && x[2] == 1 && x[3] == 1 && x[4] == 1) || // 0 for (01, 11)
                (x[1] == 1 && x[2] == 0 && x[3] == 0 && x[4] == 1);   // 1 for (10, 01)
endmodule