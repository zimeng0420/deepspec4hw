module top_module (
    input [4:1] x,
    output logic f
);

    assign f = (x[4] == 0 && x[3] == 0 && x[2] == 0) || // 00 00
               (x[4] == 0 && x[3] == 0 && x[2] == 1) || // 00 10
               (x[4] == 1 && x[3] == 1 && x[2] == 0) || // 10 00
               (x[4] == 1 && x[3] == 1 && x[2] == 1) || // 11 00
               (x[4] == 0 && x[3] == 1 && x[2] == 1) || // 11 01
               (x[4] == 1 && x[3] == 0 && x[2] == 1);   // 10 01

endmodule