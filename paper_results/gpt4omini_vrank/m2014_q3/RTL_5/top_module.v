module top_module (
    input [4:1] x,
    output logic f
);
    assign f = (x[4] == 1'b1 && x[3] == 1'b1) || // x[4]=1, x[3]=1 -> f=1 (cells (11, 00), (11, 01))
                (x[4] == 1'b0 && x[3] == 1'b1 && x[2] == 1'b1) || // x[3]=1, x[4]=0, x[2]=1 -> f=1 (cell (11, 10))
                (x[4] == 1'b1 && x[3] == 1'b0 && x[2] == 1'b0) || // x[3]=0, x[4]=1, x[1]=0 -> f=1 (cell (10, 00))
                (x[4] == 1'b0 && x[3] == 1'b1 && x[2] == 1'b0); // x[4]=0, x[3]=1, x[2]=0 -> f=0 (cell (01, 10))
endmodule